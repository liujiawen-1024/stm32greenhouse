/*
 * 6 个按键共用一个回调：20ms 软件消抖后把按键序号投递给 ControlTask。
 * 中断里只写普通变量并置标志，不调用 FreeRTOS API，
 * 因此不受 configMAX_SYSCALL_INTERRUPT_PRIORITY 约束。
 */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  static uint32_t last_tick[KEY_IDX_MAX] = {0};
  const uint32_t now = HAL_GetTick();
  uint8_t idx;

  switch (GPIO_Pin) {
    case KEY1_Pin: idx = KEY_IDX_1; break;
    case KEY2_Pin: idx = KEY_IDX_2; break;
    case KEY3_Pin: idx = KEY_IDX_3; break;
    case KEY4_Pin: idx = KEY_IDX_4; break;
    case KEY5_Pin: idx = KEY_IDX_5; break;
    case KEY6_Pin: idx = KEY_IDX_6; break;
    default: return;
  }

  if ((now - last_tick[idx]) < KEY_DEBOUNCE_MS) {
    return;
  }
  last_tick[idx] = now;

  EV_KeyPost(idx);   /* 后到的会覆盖先到的：只保留最后一个按键 */
}

